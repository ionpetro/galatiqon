import { useState } from 'react'

function Code({ children }: { children: string }) {
  const [copied, setCopied] = useState(false)
  const html = children
    .split('\n')
    .map((l) => (l.trimStart().startsWith('#') ? `<span class="c">${esc(l)}</span>` : esc(l).replace(/^(\s*)(sudo|git|gb|galatiqon-\w+|python3(?:\.\d+)?|systemctl|journalctl|pnpm|curl|cd|ssh)\b/, '$1<span class="k">$2</span>')))
    .join('\n')
  return (
    <div className="relative group">
      <pre className="code" dangerouslySetInnerHTML={{ __html: html }} />
      <button onClick={() => { navigator.clipboard?.writeText(children).then(() => { setCopied(true); setTimeout(() => setCopied(false), 1200) }) }}
        className="absolute top-2.5 right-2.5 pill opacity-0 group-hover:opacity-100 transition hover:border-mint hover:text-mint">{copied ? 'copied' : 'copy'}</button>
    </div>
  )
}
const esc = (s: string) => s.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]!))

function Step({ n, title, children }: { n: number; title: string; children: React.ReactNode }) {
  return (
    <li className="relative pl-14 pb-10 last:pb-0">
      <div className="absolute left-0 top-0 w-10 h-10 rounded-full border border-line bg-bg-2 flex items-center justify-center mono text-xs text-mint">{String(n).padStart(2, '0')}</div>
      <h3 className="display text-lg font-medium mb-3 pt-2">{title}</h3>
      <div className="flex flex-col gap-3 text-sm text-ink-dim leading-relaxed [&_strong]:text-ink [&_a]:text-mint [&_a:hover]:underline">{children}</div>
    </li>
  )
}

